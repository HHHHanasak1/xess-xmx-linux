#!/usr/bin/env python3
"""gen_placeholders.py <out.inc> [fxc path]
Generates the shim's placeholder compute shaders (shim/src/dll/placeholders.inc): two DXBC templates, compiled by fxc,
that store l(MAGIC, LO, HI) to u0 with one store_raw. For a CM kernel the shim writes the kernel's 64-bit hash over LO
and HI (low dword first) in a copy and recomputes the DXBC checksum; the patched ANV reads the hash back from the
store's constants (anv_cm_placeholder_hash() in src/intel/vulkan/anv_cm.c). The kernel template has numthreads
(1, 1, KERNEL_Z), the self-test template (1, 1, CANARY_Z); the shim fills the latter with the driver's ANV_CM_CANARY_LO
/ ANV_CM_CANARY_HI. tools/check_placeholders.py checks the result against the driver. Needs fxc.exe (Windows SDK); under
WSL the Windows fxc.exe can be passed (paths are converted with wslpath)."""
import glob, os, struct, subprocess, sys, tempfile

MAGIC = 0x584D5843
KERNEL_Z = 23
CANARY_Z = 19
# what fxc compiles in place of the hash; each must occur exactly once in the blob
SENTINEL_LO = 0x13579BDF
SENTINEL_HI = 0x2468ACE0


def winpath(p):
    """the path as fxc.exe sees it (only differs when this runs under WSL)"""
    if os.name == "posix" and FXC.lower().endswith(".exe"):
        return subprocess.run(["wslpath", "-w", p], capture_output=True, text=True, check=True).stdout.strip()
    return p


def compile_template(tmp, z):
    hl = os.path.join(tmp, "p%d.hlsl" % z)
    with open(hl, "w") as f:
        f.write("RWByteAddressBuffer u0 : register(u0);\n"
                "[numthreads(1,1,%d)] void main() { u0.Store3(0, uint3(0x%08X, 0x%08X, 0x%08X)); }\n"
                % (z, MAGIC, SENTINEL_LO, SENTINEL_HI))
    co = os.path.join(tmp, "p%d.cso" % z)
    r = subprocess.run([FXC, "/nologo", "/T", "cs_5_0", "/E", "main", "/Fo", winpath(co), winpath(hl)],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stdout, r.stderr)
        sys.exit(1)
    data = open(co, "rb").read()
    words = [struct.unpack_from("<I", data, o)[0] for o in range(0, len(data) - 3, 4)]
    lo = [i for i, w in enumerate(words) if w == SENTINEL_LO]
    hi = [i for i, w in enumerate(words) if w == SENTINEL_HI]
    if len(lo) != 1 or len(hi) != 1 or hi[0] != lo[0] + 1 or words[lo[0] - 1] != MAGIC:
        sys.exit("numthreads %d: the store immediates are not l(magic, lo, hi) exactly once in the blob" % z)
    return data, 4 * lo[0]


def main():
    global FXC
    out = sys.argv[1]
    FXC = sys.argv[2] if len(sys.argv) > 2 else os.environ.get("FXC") or \
        (sorted(glob.glob("C:/Program Files (x86)/Windows Kits/10/bin/*/x64/fxc.exe")) or ["fxc"])[-1]
    tmp = tempfile.mkdtemp(prefix="placeholders")
    kernel, kernel_at = compile_template(tmp, KERNEL_Z)
    canary, canary_at = compile_template(tmp, CANARY_Z)
    arr = lambda name, data: "static const unsigned char %s[] = {%s};\n" % (name, ",".join("0x%02x" % b for b in data))
    src = ("// generated by tools/gen_placeholders.py: the placeholder DXBC compute shaders. Each stores l(0x%08X, lo, hi)\n"
           "// to u0 in one store_raw; the shim writes the kernel's hash (low dword first) or the self-test values over\n"
           "// lo and hi in a copy and recomputes the checksum. Kernel: numthreads(1, 1, %d); self-test: (1, 1, %d).\n"
           % (MAGIC, KERNEL_Z, CANARY_Z)
           + arr("kPlaceholderKernel", kernel) + arr("kPlaceholderCanary", canary) +
           "static const size_t kPlaceholderKernelHashAt = %d;   // byte offset of lo, hi follows\n" % kernel_at +
           "static const size_t kPlaceholderCanaryHashAt = %d;\n" % canary_at)
    with open(out, "w", newline="\n") as f:
        f.write(src)
    print("wrote", out)


if __name__ == "__main__":
    main()
