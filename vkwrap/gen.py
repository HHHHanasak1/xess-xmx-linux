#!/usr/bin/env python3
"""gen.py <exports.txt> <out dir>: the forwarding part of vulkan-1.dll.
For every function the Vulkan loader exports (exports.txt, one name per line, taken from Proton's vulkan-1.dll) except
the ones vkwrap.c implements itself, writes
  stubs.asm      (ml64) w_<name>: jmp [p_<name>], p_<name> filled by vkwrap.c from the system's vulkan-1.dll
  names.h        X(<name>) for every forwarded function, in the order of the pointer table
  vulkan-1.def   the exports, <name>=w_<name> (or the C function for the ones vkwrap.c implements)"""
import os, sys

OWN = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr", "vkCreateDevice"}   # implemented in vkwrap.c
names = [n.strip() for n in open(sys.argv[1]) if n.strip()]
out = sys.argv[2]
os.makedirs(out, exist_ok=True)
fwd = [n for n in names if n not in OWN]
with open(os.path.join(out, "stubs.asm"), "w") as f:
    f.write("; generated by gen.py: one jump per forwarded Vulkan function\n.data\n")
    f.write("PUBLIC vkw_table\nvkw_table LABEL QWORD\n")
    for n in fwd:
        f.write("p_%s QWORD 0\n" % n)
    f.write(".code\n")
    for n in fwd:
        f.write("w_%s PROC\n  jmp QWORD PTR [p_%s]\nw_%s ENDP\n" % (n, n, n))
    f.write("END\n")
with open(os.path.join(out, "names.h"), "w") as f:
    f.write("/* generated by gen.py: the forwarded functions, in the order of vkw_table */\n")
    for n in fwd:
        f.write("X(%s)\n" % n)
with open(os.path.join(out, "vulkan-1.def"), "w") as f:
    f.write("LIBRARY vulkan-1\nEXPORTS\n")
    for n in names:
        f.write("    %s\n" % n if n in OWN else "    %s=w_%s\n" % (n, n))
print("%d exports, %d forwarded" % (len(names), len(fwd)))
