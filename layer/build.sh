#!/bin/bash
# build.sh [out dir] - build the layer (Linux: gcc, glslangValidator, python3). VULKAN_HEADERS: a Vulkan-Headers
# checkout whose include/ is used instead of the system headers.
set -eu
L="$(cd "$(dirname "$0")" && pwd)"
S="$L/src"; B3="$L/third_party/blake3"
O="${1:-$L/out}"
mkdir -p "$O/gen"
INC=(-I"$O/gen")
[ -n "${VULKAN_HEADERS:-}" ] && INC+=(-I"$VULKAN_HEADERS/include")
# the GPU list (gpu-ids.txt) for src/gens.h
sh "$L/tools/gen_gpu_ids.sh" "$L/gpu-ids.txt" "$O/gen/gpu_ids.inc"
# the template shader as a C array of SPIR-V words
glslangValidator -V --target-env vulkan1.1 -S comp "$S/template.comp" -o "$O/gen/template.spv" >/dev/null
python3 - "$O/gen/template.spv" "$O/gen/template_spv.h" <<'EOF'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack(f'<{len(d) // 4}I', d)
rows = [', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)]
open(sys.argv[2], 'w').write('/* generated by build.sh from src/template.comp */\nstatic const uint32_t xmx_template_spv[] = {\n   '
                             + ',\n   '.join(rows) + '\n};\n')
EOF
gcc -std=c11 -O2 -g -fPIC -shared -fvisibility=hidden -Wall -Wextra -Werror -Wno-format-truncation \
  -Wno-unused-parameter -Wno-missing-field-initializers "${INC[@]}" \
  -DBLAKE3_NO_SSE2 -DBLAKE3_NO_SSE41 -DBLAKE3_NO_AVX2 -DBLAKE3_NO_AVX512 -DBLAKE3_USE_NEON=0 \
  -o "$O/libVkLayer_xess_xmx.so" "$S/layer.c" "$S/placeholder.c" "$S/cmk.c" "$S/compile.c" "$S/prologue.c" \
  "$S/anvbin.c" "$S/map.c" "$S/pace.c" "$S/prof.c" "$B3/blake3.c" "$B3/blake3_dispatch.c" "$B3/blake3_portable.c" \
  -Wl,--no-undefined -lpthread
cp "$L/VkLayer_xess_xmx.json" "$O/"
echo "built $O/libVkLayer_xess_xmx.so"
