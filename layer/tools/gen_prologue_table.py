#!/usr/bin/env python3
"""gen_prologue_table.py <out.inc> - the encodings of the prologue's instruction forms (prologue_asm.py) as C tables,
one per IGA platform the layer serves (Xe3, Xe2), so that the layer builds a kernel's prologue without an assembler:
fixed instructions as they are, the forms with an immediate as one encoding plus the byte offset of the 32-bit
immediate. Needs IGC (see prologue_asm.py). tests/build.sh checks the C result against prologue_asm.py for a whole
kernel set on each platform."""
import sys

import prologue_asm as P

# (C comment name, IGA platform, prologue.h enum value)
TABLES = (('Xe3', P.IGA_XE3, 'XMX_ISA_XE3'), ('Xe2', P.IGA_XE2, 'XMX_ISA_XE2'))


def one(text, gen):
    b = P.assemble(text + '\n', gen)
    assert len(b) == 16, f'{len(b)} bytes for {text!r}'
    return b


def with_imm(form, gen):
    """encoding with immediate 0 and the offset of the immediate's 4 bytes (little endian)"""
    a, b = one(form(0x12345678), gen), one(form(0x9abcdef0), gen)
    diff = [i for i in range(16) if a[i] != b[i]]
    assert diff == list(range(diff[0], diff[0] + 4)), f'immediate not in 4 adjacent bytes: {diff}'
    o = diff[0]
    assert a[o:o + 4] == (0x12345678).to_bytes(4, 'little') and b[o:o + 4] == (0x9abcdef0).to_bytes(4, 'little')
    z = one(form(0), gen)
    assert z[:o] == a[:o] and z[o + 4:] == a[o + 4:] and z[o:o + 4] == b'\0\0\0\0'
    return z, o


def arr(b):
    return '{ ' + ', '.join(f'0x{x:02x}' for x in b) + ' }'


def table(name, gen, enum):
    f = [f'   .clr = {{ {arr(one(P.clr(2), gen))}, {arr(one(P.clr(3), gen))} }},']
    imms, offs = [], set()
    for s in range(32):
        z, o = with_imm(lambda v, s=s: P.imm(s, v), gen)
        imms.append(arr(z))
        offs.add(o)
    assert len(offs) == 1
    f.append('   .imm = {\n      ' + ',\n      '.join(imms) + ' },')
    f.append(f'   .imm_off = {offs.pop()},')
    gcs = [arr(one(P.gc(s, i), gen)) for s in range(32) for i in range(3)]
    f.append('   .gc = {\n      ' + ',\n      '.join(gcs) + ' },')
    f.append(f'   .tid = {arr(one(P.tid(), gen))},')
    f.append(f'   .r1clr = {arr(one(P.r1clr(), gen))},')
    for field, form in (('and41', P.and41), ('shr42', P.shr42), ('and42', P.and42), ('shr43', P.shr43)):
        z, o = with_imm(form, gen)
        f.append(f'   .{field} = {arr(z)}, .{field}_off = {o},')
    f.append(f'   .lid = {{ {", ".join(arr(one(P.lid(i), gen)) for i in range(3))} }},')
    return f'[{enum}] = {{   /* {name}: IGA platform 0x{gen:x} */\n' + '\n'.join(f) + '\n}'


def main():
    out = ['/* generated by layer/tools/gen_prologue_table.py from layer/tools/prologue_asm.py - do not edit.',
           ' * The encodings of the prologue instruction forms per IGA platform (64-byte GRF); see prologue.c. */',
           'static const struct pro_table pro_tables[XMX_ISA_COUNT] = {',
           ',\n'.join(table(*t) for t in TABLES),
           '};']
    open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
    print(f'{sys.argv[1]}: {len(TABLES)} platforms x {2 + 32 + 96 + 2 + 4 + 3} encodings')


if __name__ == '__main__':
    main()
