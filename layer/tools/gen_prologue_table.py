#!/usr/bin/env python3
"""gen_prologue_table.py <out.inc> - the encodings of the prologue's instruction forms (prologue_asm.py) as a C table,
so that the layer builds a kernel's prologue without an assembler: fixed instructions as they are, the forms with an
immediate as one encoding plus the byte offset of the 32-bit immediate. Needs IGC (see prologue_asm.py).
tests/test_prologue.c checks the C result against prologue_asm.py for a whole kernel set."""
import sys

import prologue_asm as P


def one(text):
    b = P.assemble(text + '\n')
    assert len(b) == 16, f'{len(b)} bytes for {text!r}'
    return b


def with_imm(form):
    """encoding with immediate 0 and the offset of the immediate's 4 bytes (little endian)"""
    a, b = one(form(0x12345678)), one(form(0x9abcdef0))
    diff = [i for i in range(16) if a[i] != b[i]]
    assert diff == list(range(diff[0], diff[0] + 4)), f'immediate not in 4 adjacent bytes: {diff}'
    o = diff[0]
    assert a[o:o + 4] == (0x12345678).to_bytes(4, 'little') and b[o:o + 4] == (0x9abcdef0).to_bytes(4, 'little')
    z = one(form(0))
    assert z[:o] == a[:o] and z[o + 4:] == a[o + 4:] and z[o:o + 4] == b'\0\0\0\0'
    return z, o


def arr(b):
    return '{ ' + ', '.join(f'0x{x:02x}' for x in b) + ' }'


def main():
    out = []
    out.append('/* generated by layer/tools/gen_prologue_table.py from layer/tools/prologue_asm.py - do not edit.')
    out.append(' * Xe3 (64-byte GRF) encodings of the prologue instruction forms; see prologue.c. */')
    out.append(f'static const uint8_t PRO_CLR[2][16] = {{ {arr(one(P.clr(2)))}, {arr(one(P.clr(3)))} }};')
    imms, offs = [], set()
    for s in range(32):
        z, o = with_imm(lambda v, s=s: P.imm(s, v))
        imms.append(arr(z))
        offs.add(o)
    assert len(offs) == 1
    out.append(f'static const uint8_t PRO_IMM[32][16] = {{\n   ' + ',\n   '.join(imms) + ' };')
    out.append(f'#define PRO_IMM_OFF {offs.pop()}')
    gcs = [arr(one(P.gc(s, i))) for s in range(32) for i in range(3)]
    out.append(f'static const uint8_t PRO_GC[32 * 3][16] = {{\n   ' + ',\n   '.join(gcs) + ' };')
    out.append(f'static const uint8_t PRO_TID[16] = {arr(one(P.tid()))};')
    out.append(f'static const uint8_t PRO_R1CLR[16] = {arr(one(P.r1clr()))};')
    for name, form in (('AND41', P.and41), ('SHR42', P.shr42), ('AND42', P.and42), ('SHR43', P.shr43)):
        z, o = with_imm(form)
        out.append(f'static const uint8_t PRO_{name}[16] = {arr(z)};')
        out.append(f'#define PRO_{name}_OFF {o}')
    out.append(f'static const uint8_t PRO_LID[3][16] = {{ {", ".join(arr(one(P.lid(i))) for i in range(3))} }};')
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
    print(f'{sys.argv[1]}: {2 + 32 + 96 + 2 + 4 + 3} encodings')


if __name__ == '__main__':
    main()
